// リリース署名の設定を keystore.properties から読む。
// このファイルは .gitignore 済み。無ければ署名なし（デバッグビルドのみ）で動く。
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val hasReleaseKeystore = keystorePropertiesFile.exists()

android {
    namespace = "io.github.rutar999.appshelf"
    compileSdk = 36

    defaultConfig {
        // ★ Play に一度アップロードすると変更不可。GitHub アカウント名を使って一意性を確保している。
        applicationId = "io.github.rutar999.appshelf"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables { useSupportLibrary = true }
    }

    signingConfigs {
        if (hasReleaseKeystore) {
            create("release") {
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            if (hasReleaseKeystore) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        // 設定画面でバージョン名を出すために BuildConfig を生成する
        buildConfig = true
    }

    lint {
        // ObsoleteSdkInt: minSdk 26 なので mipmap-anydpi-v26 の -v26 は理屈上は不要、
        // と Lint は言うが、実際に外すと AAPT2 がアダプティブアイコンを解決できず
        // 「resource mipmap/ic_launcher not found」でビルドが落ちる。
        // Android Studio の新規プロジェクトテンプレートも -v26 付きのままなので、それに従う。
        disable += "ObsoleteSdkInt"
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

kotlin {
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_17)
    }
}

